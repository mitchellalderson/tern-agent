#[test]
fn auto_table() {
    for c in AUTO {
        assert_eq!(classify(c), Verdict::Auto, "should be automatic: {c:?}");
    }
}

#[test]
fn ask_table() {
    for c in ASK {
        assert!(
            matches!(classify(c), Verdict::Ask(_)),
            "should ask: {c:?} (got {:?})",
            classify(c)
        );
    }
    assert!(AUTO.len() + ASK.len() >= 60);
}

#[test]
fn the_reason_is_plain_words() {
    match classify("rm -rf ~") {
        Verdict::Ask(w) => assert!(w.contains("outside this folder"), "{w}"),
        v => panic!("{v:?}"),
    }
}
